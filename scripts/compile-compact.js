fs.writeFileSync(path.join(contractDir, 'index.cjs'), cjsContent, 'utf8');

// Also write index.ts barrel export
const barrelExport = `export * from './contract/index.d';
export { default as contractInfo } from './keys/contract_info.json';
`;
fs.writeFileSync(path.join(managedDir, 'index.ts'), barrelExport, 'utf8');

console.log('✅ [StellarRise] Compact contract compiled successfully!');
console.log(`📁 Managed artifacts generated at: ${managedDir}`);
console.log(`🔑 Prover/Verifier keys created for: ${circuits.map(c => c.name).join(', ')}`);
